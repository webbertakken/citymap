// Writes packages/ground-plan/src/fixed/directions.ts: the quarter-wave cosine table, the one place floating point is
// used. The table is committed and checked by its checksum test; run this only to reproduce it.
// Usage: bun scripts/generate-directions.ts
import { join } from "node:path";

const TURN = 4096;
const DIRECTION = 4096;
const values = Array.from({ length: TURN / 4 + 1 }, (_, i) =>
  Math.round(Math.cos((2 * Math.PI * i) / TURN) * DIRECTION),
);
const rows = Array.from(
  { length: Math.ceil(values.length / 16) },
  (_, r) => `  ${values.slice(r * 16, r * 16 + 16).join(", ")},`,
);
const text = [
  "// Generated by scripts/generate-directions.ts; do not edit. round(cos(2π i / 4096) × 4096) for i = 0 to 1024.",
  "export const COSINE: readonly number[] = [",
  ...rows,
  "];",
  "",
].join("\n");
await Bun.write(join(import.meta.dirname, "../packages/ground-plan/src/fixed/directions.ts"), text);
console.log(`[directions] ${values.length} values written`);
