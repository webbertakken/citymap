// Generates src/fixed/directions.ts: the quarter-wave cosine table behind every direction in the engine.
// Floating point is allowed here only; the committed table is the source of truth for every implementation.
// Usage: bun scripts/generate-directions.ts
const TURN = 4096;
const DIRECTION = 4096;
const cosine = Array.from({ length: TURN / 4 + 1 }, (_, i) =>
  Math.round(Math.cos((2 * Math.PI * i) / TURN) * DIRECTION),
);
const rows: string[] = [];
for (let i = 0; i < cosine.length; i += 16) rows.push(`  ${cosine.slice(i, i + 16).join(", ")},`);
const source = `// Generated by scripts/generate-directions.ts; do not edit. round(cos(2π i / 4096) × 4096) for i = 0 to 1024.
export const COSINE: readonly number[] = [
${rows.join("\n")}
];
`;
await Bun.write(new URL("../src/fixed/directions.ts", import.meta.url), source);
console.log(`[directions] wrote ${cosine.length} entries`);
